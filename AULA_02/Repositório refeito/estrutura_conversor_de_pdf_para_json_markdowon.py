# Cria as subpastas
base = Path("/content/aula_2")
(pasta_pdfs := base / "pdfs").mkdir(exist_ok=True)
(pasta_md := base / "markdown").mkdir(exist_ok=True)
(pasta_json := base / "json").mkdir(exist_ok=True)
(pasta_meta := base / "metadados").mkdir(exist_ok=True)

# Move PDFs
for f in base.glob("*.pdf"):
    f.rename(pasta_pdfs / f.name)

# Move Markdowns
for f in base.glob("*.md"):
    f.rename(pasta_md / f.name)

# Move JSONs completos (sem "_metadados")
for f in base.glob("*.json"):
    if "_metadados" not in f.name:
        f.rename(pasta_json / f.name)

# Move metadados
for f in base.glob("*.json"):
    if "_metadados" in f.name:
        f.rename(pasta_meta / f.name)

# Move o resumo geral também
geral = base / "metadados_aula_2.json"
if geral.exists():
    geral.rename(pasta_meta / geral.name)

print("✅ Pastas organizadas!")
