import json
import re
from pathlib import Path

pasta_saida = Path("/content/aula_2")
arquivos_json = sorted([f for f in pasta_saida.glob("*.json") if "_metadados" not in f.name])

resultados = []

for json_file in arquivos_json:
    with open(json_file, "r", encoding="utf-8") as f:
        dados = json.load(f)

    # Junta todos os itens da lista "texts" (que é a estrutura comum dos seus JSONs)
    itens = dados.get("texts", [])

    # ------------------------------------------------------------
    # 1) TÍTULO: Primeiro [section_header] com mais de 10 caracteres
    # ------------------------------------------------------------
    titulo = "Não identificado"
    for item in itens:
        if item.get("label") == "section_header":
            candidato = item.get("text", "").strip()
            if len(candidato) > 10:
                titulo = candidato
                break

    # ------------------------------------------------------------
    # 2) AUTORES: Linha logo após o título ou que contenha "1,"
    # ------------------------------------------------------------
    autores = []
    modo_captura = False
    for item in itens:
        texto = item.get("text", "").strip()
        label = item.get("label", "")

        # Ativa a captura quando encontra o título
        if label == "section_header" and len(texto) > 10:
            modo_captura = True
            continue

        if modo_captura and label == "text":
            # Se parece nome de autor (tem número 1, 2... ou asterisco)
            if re.search(r"\b[A-ZÀ-Ú][a-zà-ú]+.*\b\d\b", texto) or "*" in texto:
                # Limpa números e asteriscos
                nomes_limpos = re.sub(r"[*\d]", "", texto).strip()
                # Se tiver vários autores separados por espaço grande ou tab
                for nome in re.split(r"\s{2,}|(?<=[a-z])\s+(?=[A-ZÀ-Ú])", nomes_limpos):
                    nome = nome.strip().rstrip(",").strip()
                    if len(nome.split()) >= 2 and nome not in autores:
                        autores.append(nome)
                break  # Já pegou a linha de autores
            # Se não tem número mas parece nome próprio (2+ palavras com maiúsculas)
            elif re.match(r"^[A-ZÀ-Ú][a-zà-ú]+ [A-ZÀ-Ú][a-zà-ú]+", texto) and len(texto.split()) >= 2:
                # Garante que não é resumo/palavra-chave
                if not any(p in texto.lower() for p in ["resumo", "abstract", "palavra", "keyword"]):
                    autores.append(texto)
                    break

    # ------------------------------------------------------------
    # 3) ANO: Procura "2025", "2026", etc. nos page_headers ou datas
    # ------------------------------------------------------------
    ano = "Não identificado"
    for item in itens:
        texto = item.get("text", "").strip() + " " + item.get("label", "")
        # Busca ano em contextos de publicação
        match = re.search(r"(?:vol\.?\s*\d+\s*\w*\s*|publicado em |Aceito em |aprovado em )(\d{4})", texto, re.IGNORECASE)
        if match:
            ano = match.group(1)
            break
    if ano == "Não identificado":
        # Plano B: qualquer ano entre 2020-2026 nos primeiros textos
        for item in itens[:10]:
            texto = item.get("text", "")
            match = re.search(r"\b(20[2-9]\d|2030)\b", texto)
            if match:
                ano = match.group(1)
                break

    # ------------------------------------------------------------
    # 4) Monta e salva o resultado
    # ------------------------------------------------------------
    resultado = {
        "arquivo_original": json_file.name.replace(".json", ".pdf"),
        "titulo": titulo,
        "autores": autores if autores else ["Não identificado"],
        "ano_edicao": int(ano) if ano.isdigit() else ano
    }
    resultados.append(resultado)

    nome_saida = pasta_saida / f"{json_file.stem}_metadados.json"
    with open(nome_saida, "w", encoding="utf-8") as f:
        json.dump(resultado, f, ensure_ascii=False, indent=2)

    print(f"✅ {json_file.name}")
    print(f"   Título: {titulo}")
    print(f"   Autores: {autores}")
    print(f"   Ano: {ano}\n")

# Salva resumo geral
resumo_path = pasta_saida / "metadados_aula_2.json"
with open(resumo_path, "w", encoding="utf-8") as f:
    json.dump(resultados, f, ensure_ascii=False, indent=2)

print(f"🎉 Resumo geral salvo em: aula_2/{resumo_path.name}")

